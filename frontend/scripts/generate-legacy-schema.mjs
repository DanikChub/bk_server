import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const catalog = JSON.parse(readFileSync(path.join(root, 'database/tests/expected-catalog.json'), 'utf8'));
const builders = new Set();
function column(c) {
  const name = JSON.stringify(c.name);
  let expression;
  if (c.type === 'uuid') expression = `uuid(${name})`;
  else if (c.type === 'boolean') expression = `boolean(${name})`;
  else if (c.type === 'integer') expression = `integer(${name})`;
  else if (c.type === 'smallint') expression = `smallint(${name})`;
  else if (c.type === 'bigint') expression = `bigint(${name}, { mode: 'bigint' })`;
  else if (c.type.startsWith('character varying')) expression = `varchar(${name}, { length: ${c.type.match(/\d+/)[0]} })`;
  else if (c.type.startsWith('timestamp')) expression = `timestamp(${name}, { mode: 'string', withTimezone: ${c.type.includes('with time zone')} })`;
  else if (c.type === 'double precision') expression = `doublePrecision(${name})`;
  else if (c.type === 'interval') expression = `interval(${name})`;
  else if (c.type === 'jsonb') expression = `jsonb(${name})`;
  else if (c.type === 'text') expression = `text(${name})`;
  else throw new Error(`Unmapped type: ${c.table}.${c.name}: ${c.type}`);
  builders.add(expression.slice(0, expression.indexOf('(')));
  if (c.notNull) expression += '.notNull()';
  if (c.default !== null) expression += `.default(sql.raw(${JSON.stringify(c.default)}))`;
  return `  ${name}: ${expression},`;
}
const tables = catalog.tables.map(table => {
  const fields = catalog.columns.filter(c => c.table === table).map(column);
  return `export const ${table} = pgTable(${JSON.stringify(table)}, {\n${fields.join('\n')}\n});`;
});
const target = path.join(root, 'frontend/src/server/db');
mkdirSync(target, { recursive: true });
writeFileSync(path.join(target, 'legacy-schema.ts'), `// Generated by scripts/generate-legacy-schema.mjs from the independent legacy catalog.\n// Read/query mapping only. SQL migrations own keys, identity, indexes, functions and triggers.\nimport { sql } from 'drizzle-orm';\nimport { pgTable, ${[...builders].sort().join(', ')} } from 'drizzle-orm/pg-core';\n\n${tables.join('\n\n')}\n`);
writeFileSync(path.join(target, 'legacy-catalog.json'), JSON.stringify({ tables: catalog.tables, columns: catalog.columns }, null, 2) + '\n');
console.log(`Generated ${catalog.tables.length} tables, ${catalog.columns.length} columns`);
